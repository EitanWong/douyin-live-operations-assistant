export function appendWorkspaceGuide(parent,key) {
 const guide=guides[key];if(!guide)return false;
 const document=parent.ownerDocument,section=document.createElement('section');section.className='workspace-help-guide';section.dataset.workspaceGuide=key;
 for(const [title,tag,items] of [['能帮你做什么','p',[guide.purpose]],['怎么使用','ol',guide.steps],['使用提醒','ul',guide.tips]]){
  const heading=document.createElement('h4');heading.textContent=title;const body=document.createElement(tag);
  if(tag==='p')body.textContent=items[0];
  else for(const text of items){const item=document.createElement('li');item.textContent=text;body.append(item);}
  section.append(heading,body);
 }
 parent.append(section);return true;
}
